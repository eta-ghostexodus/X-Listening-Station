import fs from 'node:fs';
import assert from 'node:assert/strict';
const main = fs.readFileSync(new URL('../electron/main.cjs', import.meta.url), 'utf8');
const renderer = fs.readFileSync(new URL('../src/main.tsx', import.meta.url), 'utf8');
const pkg = JSON.parse(fs.readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
const prep = fs.readFileSync(new URL('./prepare-tor.mjs', import.meta.url), 'utf8');
const installer = fs.readFileSync(new URL('../INSTALL_WINDOWS.bat', import.meta.url), 'utf8');
assert.equal(pkg.version, '3.4.1');
assert.equal(pkg.scripts['prepare:tor'], 'node scripts/prepare-tor.mjs');
