assert(pkg.build.files.includes('build/icon.ico'));
assert.equal(pkg.build.win.icon, 'build/icon.ico');
assert.equal(pkg.build.nsis.installerIcon, 'build/icon.ico');
assert(main.includes("const { spawn } = require('node:child_process');"));
